#!/usr/bin/env python3
"""Bake tests/host/spawner_path.vectors into a C string header.

The coverage tool (tools/host_coverage.py) runs the linked test binary without
arguments, so the vectors have to be part of the binary as well. This script
prints the header; the test script regenerates it on every run so a changed
vector file can never go stale against a checked-in copy.

    python3 spawner_path_vectors.py [path/to/spawner_path.vectors]
"""
import pathlib
import sys


def c_string(text):
    """Render `text` as a C string literal body, one escaped line per vector."""
    out = []
    for line in text.splitlines(keepends=True):
        esc = []
        for ch in line:
            if ch == "\\":
                esc.append("\\\\")
            elif ch == '"':
                esc.append('\\"')
            elif ch == "\n":
                esc.append("\\n")
            elif ch == "\t":
                esc.append("\\t")
            elif ch == "\r":
                esc.append("\\r")
            elif 0x20 <= ord(ch) < 0x7F:
                esc.append(ch)
            else:
                esc.append("\\%03o" % ord(ch))
        out.append('    "%s"\n' % "".join(esc))
    return "".join(out)


def main():
    path = pathlib.Path(sys.argv[1] if len(sys.argv) > 1
                        else pathlib.Path(__file__).with_name("spawner_path.vectors"))
    text = path.read_text()
    body = c_string(text)
    print("/* Generated by tests/host/spawner_path_vectors.py from %s - do not edit. */" % path.name)
    print("#ifndef SPAWNER_VECTORS_H")
    print("#define SPAWNER_VECTORS_H")
    print("static const char gSpawnerVectors[] =")
    print(body, end="")
    print("    ;")
    print("#endif")


if __name__ == "__main__":
    main()
