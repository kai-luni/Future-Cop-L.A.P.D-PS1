#!/usr/bin/env python3
"""Independent expected values for the leaf-function suite (tests/host/leaf_a1_harness.c).

Nothing here is derived from the decompiled game source. Every formula comes
from a reference that exists independently of this repository:

  * isqrt_q8      - mathematics: floor(sqrt(v) * 256) == isqrt(v << 16)
  * get_tpage     - PSn00bSDK libpsn00b/include/psxgpu.h  getTPage(tp, abr, x, y)
  * get_clut      - PSn00bSDK psxgpu.h                     getClut(x, y)
  * get_tw        - Psy-Q libgpu get_tw(RECT*) / psx-spx GP0(E2h) texture window:
                    mask = (~(size - 1) & 0xFF) >> 3, offset = (pos & 0xFF) >> 3,
                    bits 0-4 maskX, 5-9 maskY, 10-14 offX, 15-19 offY
  * cd_pos_to_int - Psy-Q libcd CdPosToInt: BCD MSF -> sector, minus the 2 s
                    (150 sector) lead-in
  * park_miller   - Park & Miller "minimal standard" generator,
                    z' = 16807 * z mod (2^31 - 1) (CACM 31(10), 1988); the
                    published check value is z_10001 = 1043618065 from z_1 = 1

The script prints a C header; the test script regenerates it on every run so a
changed formula can never go stale against a checked-in copy.
"""
import math
import sys


def isqrt_q8(v):
    return math.isqrt(v << 16)


def get_tpage(tp, abr, x, y):
    return (((x & 0x3C0) >> 6) | ((y & 0x100) >> 4) | ((y & 0x200) << 2)
            | ((abr & 3) << 5) | ((tp & 3) << 7)) & 0xFFFF


def get_clut(x, y):
    return ((y << 6) | ((x >> 4) & 0x3F)) & 0xFFFF


def get_tw(x, y, w, h):
    mask_x = (~(w - 1) & 0xFF) >> 3
    mask_y = (~(h - 1) & 0xFF) >> 3
    off_x = (x & 0xFF) >> 3
    off_y = (y & 0xFF) >> 3
    return 0xE2000000 | (off_y << 15) | (off_x << 10) | (mask_y << 5) | mask_x


PM_M = 0x7FFFFFFF


def park_miller(z):
    return (16807 * z) % PM_M


def bcd(n):
    return ((n // 10) << 4) | (n % 10)


def cd_pos_to_int(m, s, f):
    return (m * 60 + s) * 75 + f - 150


SQRT_INPUTS = [0, 1, 2, 3, 4, 100, 255, 256, 65535, 65536, 1000000,
               0x7FFFFFFF, 0x80000000, 0xFFFFFFFE, 0xFFFFFFFF]
TPAGE_INPUTS = [(0, 0, 0, 0), (2, 1, 640, 256), (1, 3, 1023, 511),
                (3, 2, 960, 0), (0, 0, 64, 768), (7, 7, 0x3FF, 0x3FF)]
CLUT_INPUTS = [(0, 0), (256, 480), (1008, 511), (15, 1), (16, 0), (320, 1023)]
TW_INPUTS = [(0, 0, 0, 0), (16, 32, 64, 64), (0, 0, 256, 256),
             (248, 8, 8, 32), (-8, -16, 128, 16)]
PM_SEEDS = [1, 2, 16807, 0x7FFFFFFE, 0x40000000, 123456789, 0x7FFF, 0x10000]
CD_INPUTS = [(0, 2, 0), (0, 2, 1), (1, 0, 0), (74, 59, 74), (0, 0, 0), (12, 34, 56)]


def emit():
    out = ["/* generated by tests/host/leaf_vectors.py - do not edit */",
           "#ifndef LEAF_VECTORS_H", "#define LEAF_VECTORS_H"]
    out.append("static const u32 lv_sqrt[][2] = {")
    out += [f"    {{0x{v:08X}u, 0x{isqrt_q8(v):08X}u}}," for v in SQRT_INPUTS]
    out.append("};")
    out.append("static const s32 lv_tpage[][5] = {")
    out += [f"    {{{a}, {b}, {c}, {d}, 0x{get_tpage(a, b, c, d):04X}}},"
            for a, b, c, d in TPAGE_INPUTS]
    out.append("};")
    out.append("static const s32 lv_clut[][3] = {")
    out += [f"    {{{x}, {y}, 0x{get_clut(x, y):04X}}}," for x, y in CLUT_INPUTS]
    out.append("};")
    out.append("static const s32 lv_tw[][5] = {")
    out += [f"    {{{x}, {y}, {w}, {h}, (s32)0x{get_tw(x, y, w, h):08X}u}},"
            for x, y, w, h in TW_INPUTS]
    out.append("};")
    out.append("static const s32 lv_cd[][4] = {")
    out += [f"    {{0x{bcd(m):02X}, 0x{bcd(s):02X}, 0x{bcd(f):02X}, {cd_pos_to_int(m, s, f)}}},"
            for m, s, f in CD_INPUTS]
    out.append("};")
    out.append("static const u32 lv_pm[][2] = {")
    out += [f"    {{0x{z:08X}u, 0x{park_miller(z):08X}u}}," for z in PM_SEEDS]
    out.append("};")
    z = 1
    for _ in range(10000):
        z = park_miller(z)
    assert z == 1043618065, z  # the published check value
    out.append(f"#define LV_PM_AFTER_10000_FROM_1 {z}")
    out.append("#define LV_COUNT(a) ((int)(sizeof(a) / sizeof((a)[0])))")
    out.append("#endif")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(emit())
