static int hexval(char c)
{
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}
static int parse_hex(const char *s, unsigned char *out, int limit)
{
    int n = 0;
    while (s[0] && s[1]) {
        int a = hexval(s[0]), b = hexval(s[1]);
        if (a < 0 || b < 0) return -1;
        if (n >= limit) return -1;
        out[n++] = (unsigned char)((a << 4) | b);
        s += 2;
    }
    return n;
}
static char *token(char **cursor)
{
    char *p = *cursor, *start;
    while (*p == ' ' || *p == '\t' || *p == '\r' || *p == '\n') p++;
    while (*p == '#') { while (*p && *p != '\n') p++; while (*p == ' ' || *p == '\t' || *p == '\r' || *p == '\n') p++; }
    if (!*p) { *cursor = p; return 0; }
    start = p;
    while (*p && *p != ' ' && *p != '\t' && *p != '\r' && *p != '\n') p++;
    if (*p) *p++ = 0;
    *cursor = p; return start;
}

int main(int argc, char **argv)
{
    int fd, n, i, cases = 0, failures = 0, emit = 0;
    char *p, *f[6];
    static unsigned char raw[65536];
    unsigned int words, sum;

    if (argc < 2) { say("block: missing vector path\n"); return 2; }
    if (argc > 2 && same(argv[2], "emit")) emit = 1;
    fd = (int)sys3(4005, (long)argv[1], 0, 0);
    n = (int)sys3(4003, fd, (long)file, sizeof(file) - 1);
    sys3(4006, fd, 0, 0);
    if (n <= 0 || n >= (int)sizeof(file) - 1) { say("block: vector read error\n"); return 2; }
    file[n] = 0;
    p = file;

    if (!(f[0] = token(&p)) || !same(f[0], "SYMBOLS") || !(f[1] = token(&p))) { say("block: missing SYMBOLS\n"); return 2; }
    n = parse_hex(f[1], raw, sizeof(raw));
    if (n != 0x1c0) { say("block: symbol table size\n"); return 2; }
    for (i = 0; i < 0xe0; i++) {
        symbols[i] = (u16)(raw[i * 2] | (raw[i * 2 + 1] << 8));
        D_8009C560[i * 2] = raw[i * 2];
        D_8009C560[i * 2 + 1] = raw[i * 2 + 1];
    }
    if (func_80089A88(tableA, tableB, symbols) != 0) { say("block: table build failed\n"); return 2; }

    while ((f[0] = token(&p)) != 0) {
        if (!(f[1] = token(&p)) || !(f[2] = token(&p)) || !(f[3] = token(&p)) || !(f[4] = token(&p))) { say("block: short row\n"); return 2; }
        f[5] = token(&p); /* optional expectation of the first 128 words */
        n = parse_hex(f[2], raw, sizeof(raw));
        if (n <= 0 || (n & 1)) { say("block: bad input "); say(f[1]); say(" n="); num((unsigned int)(n < 0 ? 999999 : n)); say(" len="); num((unsigned int)len(f[2])); say("\n"); return 2; }
        for (i = 0; i < (int)(sizeof(input) / 2); i++) input[i] = 0xffff;
        for (i = 0; i < n / 2; i++) input[i] = (u16)(raw[i * 2] | (raw[i * 2 + 1] << 8));
        for (i = 0; i < OUT_WORDS; i++) output[i] = 0xdead;

        func_80089BBC(input, output);

        words = 0; sum = 0;
        while (words < OUT_WORDS && output[words] != 0xdead) { sum += output[words]; words++; }
        cases++;
        if (emit) {
            say(f[1]); say(" "); num(words); say(" "); num(sum); say(" ");
            /* Words are stored little endian so every reader parses them the same way. */
            for (i = 0; i < 128 && i < (int)words; i++) { hex8(output[i] & 0xff); hex8(output[i] >> 8); }
            say("\n");
            continue;
        }
        {
            unsigned int want_words = 0, want_sum = 0, bad = 0;
            const char *q = f[3];
            while (*q >= '0' && *q <= '9') { want_words = want_words * 10 + (unsigned int)(*q - '0'); q++; }
            q = f[4];
            while (*q >= '0' && *q <= '9') { want_sum = want_sum * 10 + (unsigned int)(*q - '0'); q++; }
            if (words != want_words || sum != want_sum) bad = 1;
            if (!bad && f[5]) {
                n = parse_hex(f[5], raw, sizeof(raw));
                if (n > 0) for (i = 0; i < n / 2 && i < (int)words; i++) {
                    if (output[i] != (u16)(raw[i * 2] | (raw[i * 2 + 1] << 8))) bad = 1;
                }
            }
            if (bad) {
                failures++; say(f[1]); say(": words="); num(words); say("/"); num(want_words);
                say(" sum="); num(sum); say("/"); num(want_sum); say("\n");
            }
        }
    }
    if (!cases) { say("block: no cases\n"); return 2; }
    if (failures) { say("FAILURES "); num(failures); say(" of "); num(cases); say("\n"); return 1; }
    say("ALL PASS (WVE block C vectors: "); num(cases); say(")\n");
    return 0;
}
